/* graph is compiled once with a Postgres checkpointer (thread memory) and Postgres store (long-term memory) */
async function getGraph() {
  if (G.__graphP) return G.__graphP;
  G.__graphP = (async () => {
    const saver = new PostgresSaver(pool as any); await saver.setup();
    const store = new PostgresStore({ connectionOptions: { connectionString: process.env.PG_URI, ssl: { rejectUnauthorized: false }, max: 3 } }); await store.setup();
    G.__store = store;
    return new StateGraph(State)
      .addNode("input_guard", inputGuard).addNode("cache", cacheLookup).addNode("llm_guard", llmInputGuard).addNode("orchestrator", orchestrator)
      .addNode("policy", (s, c) => runAgent(s, "policy", c, "Searching policies and catalogue"))
      .addNode("orders", (s, c) => runAgent(s, "orders", c, "Looking up your orders and cases"))
      .addNode("returns", (s, c) => runAgent(s, "returns", c, "Checking return eligibility"))
      .addNode("general", (s, c) => runAgent(s, "general", c, "Preparing a reply"))
      .addNode("output_guard", outputGuard).addNode("respond", respond).addNode("scope_refusal", scopeRefusal)
      .addEdge(START, "input_guard")
      .addConditionalEdges("input_guard", (s) => (s.blocked ? "respond" : "cache"), { respond: "respond", cache: "cache" })
      .addConditionalEdges("cache", (s) => (s.cached ? "output_guard" : "llm_guard"), { output_guard: "output_guard", llm_guard: "llm_guard" })
      .addConditionalEdges("llm_guard", (s) => (s.blocked ? "respond" : "orchestrator"), { respond: "respond", orchestrator: "orchestrator" })
      .addConditionalEdges("orchestrator", route, { policy: "policy", orders: "orders", returns: "returns", general: "general", scope_refusal: "scope_refusal" })
      .addEdge("policy", "output_guard").addEdge("orders", "output_guard").addEdge("returns", "output_guard").addEdge("general", "output_guard")
      .addEdge("scope_refusal", "respond").addEdge("output_guard", "respond").addEdge("respond", END)
      .compile({ checkpointer: saver, store });
  })().catch((e) => { G.__graphP = undefined; throw e; });
  return G.__graphP;
}

/* long-term memory (LangGraph store, namespace ["memory", customerId]): distil durable facts after each exchange */
async function loadMemory(cid: string) {
  const store = G.__store; if (!store) return "";
  const items = await store.search(["memory", cid], { limit: 20 });
  return items.map((i: any) => `${i.key}: ${i.value?.text}`).join("; ");
}
async function updateMemory(cid: string, user: string, bot: string) {
  try {
    const store = G.__store; if (!store) return;
    const cur = await loadMemory(cid);
    const model = llm().withStructuredOutput(z.object({ facts: z.array(z.object({ key: z.string(), value: z.string() })).max(3) }));
    const r: any = await model.invoke([new SystemMessage(
      `Extract up to 3 durable, non-sensitive facts worth remembering about this customer for future support chats (preferences, ongoing issue, preferred resolution).
Never store passwords, card numbers, OTPs or health data. Return an empty list if nothing is worth saving. Existing memory: ${cur || "none"}`),
      new HumanMessage(`Customer: ${user}\nAssistant: ${bot}`)]);
    for (const f of r.facts || []) await store.put(["memory", cid], f.key.slice(0, 60).replace(/\W+/g, "_"), { text: f.value.slice(0, 300) });
  } catch {}
}

