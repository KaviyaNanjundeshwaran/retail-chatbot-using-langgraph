/* embeds with retry on provider rate limits (Gemini free tier = 100 req/min) */
async function embedDocs(texts: string[]): Promise<number[][]> {
  const e = embedder(), out: number[][] = [];
  const size = provider() === "gemini" ? 25 : 50;
  for (let i = 0; i < texts.length; i += size) {
    const part = texts.slice(i, i + size);
    for (let attempt = 0; ; attempt++) {
      try { out.push(...(await e.embedDocuments(part))); break; }
      catch (err: any) {
        const m = /retry in ([\d.]+)s/i.exec(err.message || "");
        if (/429|quota|rate/i.test(err.message || "") && attempt < 5) await sleep(((m ? +m[1] : 30) + 2) * 1000);
        else throw err;
      }
    }
    if (provider() === "gemini" && i + size < texts.length) await sleep(30000); // stay well under the 100/min free-tier limit
  }
  return out;
}
/* query embedding with retry on provider rate limits */
async function embedQ(text: string): Promise<number[]> {
  for (let attempt = 0; ; attempt++) {
    try { return await embedder().embedQuery(text); }
    catch (err: any) {
      const m = /retry in ([\d.]+)s/i.exec(err.message || "");
      if (/429|quota|rate/i.test(err.message || "") && attempt < 3) await sleep(Math.min((m ? +m[1] : 10) + 1, 20) * 1000);
      else throw err;
    }
  }
}
async function upsertKB(rows: { source: string; id: string; content: string }[]) {
  if (!rows.length) return;
  const prov = provider();
  const vs = await embedDocs(rows.map((r) => r.content));
  for (let j = 0; j < rows.length; j++) {
    if (!vs[j]?.length) continue; // skip failed/empty embeddings
    await q(`insert into app_kb(source,source_id,content,embedding,provider) values($1,$2,$3,$4::vector,$5)
             on conflict(source,source_id) do update set content=excluded.content,embedding=excluded.embedding,provider=excluded.provider,updated_at=now()`,
      [rows[j].source, rows[j].id, rows[j].content, vec(vs[j]), prov]);
  }
}
