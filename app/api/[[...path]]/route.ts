const MCP_URL = process.env.MCP_URL || "http://127.0.0.1:3333/mcp";
const mcpUp = async () => { try { return (await fetch(MCP_URL.replace(/\/mcp$/, "/health"), { signal: AbortSignal.timeout(1500) })).ok; } catch { return false; } };
async function ensureMcp() {
  if (await mcpUp()) return;
  if (process.env.MCP_URL) throw new Error("MCP server not reachable at " + MCP_URL);
  if (!G.__mcpProc || G.__mcpProc.exitCode !== null) {
    G.__mcpProc = spawn(process.execPath, [path.join(process.cwd(), "mcp-server.mjs")], { stdio: "inherit", env: process.env, windowsHide: true });
    process.once("exit", () => { try { G.__mcpProc?.kill(); } catch {} });
  }
  for (let i = 0; i < 40; i++) { await sleep(300); if (await mcpUp()) return; }
  throw new Error("MCP server failed to start (run `node mcp-server.mjs` to see why)");
}
function jsToZod(sc: any): z.ZodTypeAny {
  let t: z.ZodTypeAny;
  if (sc?.enum) t = z.enum(sc.enum as [string, ...string[]]);
  else switch (sc?.type) {
    case "integer": { let n = z.number().int(); if (typeof sc.minimum === "number") n = n.min(sc.minimum); if (typeof sc.maximum === "number") n = n.max(sc.maximum); t = n; break; }
    case "number": t = z.number(); break;
    case "boolean": t = z.boolean(); break;
    case "array": t = z.array(jsToZod(sc.items || {})); break;
    default: t = z.string();
  }
  return sc?.description ? t.describe(sc.description) : t;
}
function toZodObject(schema: any) {
  const shape: Record<string, z.ZodTypeAny> = {}, req = new Set<string>(schema?.required || []);
  for (const [k, v] of Object.entries<any>(schema?.properties || {})) { const t = jsToZod(v); shape[k] = req.has(k) ? t : t.optional(); }
  return z.object(shape);
}
async function mcpTools(cid: string, ctx: { message: string; sessionId: string; turn: string }, grounding: string[], steps: string[]) {
  await ensureMcp();
  const token = await new SignJWT({ sid: ctx.sessionId, msg: ctx.message, turn: ctx.turn }).setSubject(cid).setAudience("mcp")
    .setProtectedHeader({ alg: "HS256" }).setExpirationTime("5m").sign(secret());
  const client = new Client({ name: "returns-agent", version: "1.0.0" });
  await client.connect(new StreamableHTTPClientTransport(new URL(MCP_URL), { requestInit: { headers: { Authorization: `Bearer ${token}` } } }));
  const listed = await client.listTools();
  const byName = (names?: string[]) => listed.tools.filter((t) => !names || names.includes(t.name)).map((t) =>
    tool(async (args: any) => {
      const r: any = await client.callTool({ name: t.name, arguments: args });
      const txt = (r.content || []).map((c: any) => c.text || "").join("");
      grounding.push(txt); steps.push(`mcp:${t.name}`);
      return txt;
    }, { name: t.name, description: t.description || "", schema: toZodObject(t.inputSchema) }));
  return { byName, close: () => client.close() };
}

