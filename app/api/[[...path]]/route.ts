/* Every LLM call goes through a pacer (requests/minute, admin-tunable via chat.llm_rpm; 0 = unlimited)
   and retries on 429 using the provider's own "retry in Ns" hint. */
async function pace() {
  const rpm = (await setting("chat")).llm_rpm ?? 14; if (!rpm) return;
  const w: number[] = (G.__llmTs ??= []);
  for (;;) {
    const now = Date.now(); while (w.length && now - w[0] > 60000) w.shift();
    if (w.length < rpm) { w.push(now); return; }
    await sleep(Math.max(250, 60000 - (now - w[0]) + 100));
  }
}
const retryable = (e: any) => /429|quota|rate.?limit|too many requests|overloaded|503/i.test(String(e?.message || e));
const retryDelay = (e: any) => { const m = /retry in ([\d.]+)s/i.exec(String(e?.message || "")); return ((m ? +m[1] : 4) + 1) * 1000; };
async function rl<T>(fn: () => Promise<T>): Promise<T> {
  for (let a = 0; ; a++) {
    await pace();
    try { return await fn(); } catch (e: any) { if (retryable(e) && a < 4) { await sleep(retryDelay(e)); continue; } throw e; }
  }
}
function rlWrap(target: any): any {
  return new Proxy(target, {
    get(t, prop) {
      const v = t[prop];
      if (prop === "invoke") return (...a: any[]) => rl(() => t.invoke(...a));
      if (prop === "withStructuredOutput" || prop === "bindTools") return (...a: any[]) => rlWrap(t[prop](...a));
      if (prop === "stream") return async function* (...a: any[]) {
        for (let att = 0; ; att++) {
          await pace(); let yielded = false;
          try { for await (const c of await t.stream(...a)) { yielded = true; yield c; } return; }
          catch (e: any) { if (!yielded && retryable(e) && att < 4) { await sleep(retryDelay(e)); continue; } throw e; }
        }
      };
      return typeof v === "function" ? v.bind(t) : v;
    },
  });
}
