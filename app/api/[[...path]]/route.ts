const ID_RE = /\b(ORD|CASE|PROD|ITEM|PAY|DEL|POL|SKU|CUS)\d{6}\b/g;
function guardOutput(text: string, ctx: { cid: string; email: string; known: string }) {
  const notes: string[] = []; let out = text || "";
  if (/AIza[0-9A-Za-z_-]{20,}|\bsk-[A-Za-z0-9]{20,}|\$2[aby]\$\d\d\$[./A-Za-z0-9]{50,}/.test(out)) { out = out.replace(/AIza[0-9A-Za-z_-]{20,}|\bsk-[A-Za-z0-9]{20,}|\$2[aby]\$\d\d\$[./A-Za-z0-9]{50,}/g, "[removed]"); notes.push("secret_redacted"); }
  out = out.replace(/\bCUS\d{6}\b/g, (m) => { if (m === ctx.cid) return m; notes.push("other_customer_redacted"); return "[redacted]"; });
  out = out.replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, (m) => { if (m.toLowerCase() === (ctx.email || "").toLowerCase()) return m; notes.push("email_redacted"); return "[redacted]"; });
  const bad = (out.match(ID_RE) || []).filter((id) => id !== ctx.cid && !ctx.known.includes(id));
  if (bad.length) notes.push("ungrounded_ids:" + bad.join(","));
  const empty = !out.trim(); if (empty) notes.push("empty_output");
  return { text: out, notes, unverified: bad.length > 0, empty };
}

